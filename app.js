var show = document.getElementById("showData");
var btns = document.getElementById("btns");

function showEcomCard(filterName) {
    show.innerHTML = ""; 

    var categoriesToRender = [];
    if (filterName === "All") {
        categoriesToRender = ["PSL", "IPL", "BPL", "CPL"];
    } else {
        categoriesToRender = [filterName];
    }

    categoriesToRender.forEach(function(cat) {
        var filteredTeams = ecomData.filter(team => team.category === cat);

        if (filteredTeams.length > 0) {
            var leagueSection = document.createElement("div");
            leagueSection.className = "league-section";

            var mainHeading = document.createElement("h2");
            mainHeading.className = "league-title";
            mainHeading.innerText = `${cat} Teams`;
            leagueSection.appendChild(mainHeading);

            var cardsWrapper = document.createElement("div");
            cardsWrapper.className = "cards-wrapper";
            leagueSection.appendChild(cardsWrapper);

            filteredTeams.forEach(function(team) {
                var cardDiv = document.createElement("div");
                cardDiv.className = "team-card";

                var imgContainer = document.createElement("div");
                imgContainer.className = "img-container";

                var squadImg = document.createElement("img");
                squadImg.setAttribute("src", team.teamPhoto);
                squadImg.className = "squad-img";
                imgContainer.appendChild(squadImg);

                var logoWrapper = document.createElement("div");
                logoWrapper.className = "logo-img-wrapper";
                
                var logoImg = document.createElement("img");
                logoImg.setAttribute("src", team.image);
                logoImg.className = "logo-img";
                logoWrapper.appendChild(logoImg);
                imgContainer.appendChild(logoWrapper);

                cardDiv.appendChild(imgContainer);

                var cardContent = document.createElement("div");
                cardContent.className = "card-content";

                var categoryTag = document.createElement("div");
                categoryTag.className = "team-category";
                categoryTag.innerText = team.category;
                cardContent.appendChild(categoryTag);

                var h3 = document.createElement("h3");
                h3.className = "team-name";
                h3.innerText = team.name;
                cardContent.appendChild(h3);

                var actionBtn = document.createElement("button");
                actionBtn.className = "chase-btn";
                actionBtn.innerText = "Chase Now";
                actionBtn.onclick = function() {
                    alert("Chasing squad details for: " + team.name);
                };
                cardContent.appendChild(actionBtn);

                cardDiv.appendChild(cardContent);
                cardsWrapper.appendChild(cardDiv);
            });

            show.appendChild(leagueSection);
        }
    });
}

var categoryName = ["All", "PSL", "IPL", "BPL", "CPL"];

categoryName.forEach(function(cat, index) {
    var btn = document.createElement("button");
    btn.innerText = cat;
    if (index === 0) btn.className = "active";

    btn.onclick = function() {
        var allButtons = btns.querySelectorAll("button");
        allButtons.forEach(b => b.classList.remove("active"));
        btn.classList.add("active");
        showEcomCard(cat);
        document.getElementById("search").value = ""; 
    };
    btns.appendChild(btn);
});

