function searchItem() {
    var query = document.getElementById("search").value.toLowerCase().trim();
    var sections = show.querySelectorAll(".league-section");

    sections.forEach(function(section) {
        var cards = section.querySelectorAll(".team-card");
        var visibleCardsCount = 0;

        cards.forEach(function(card) {
            var nameEl = card.querySelector(".team-name");
            var name = nameEl ? nameEl.innerText.toLowerCase() : "";

            var catEl = card.querySelector(".team-category");
            var category = catEl ? catEl.innerText.toLowerCase() : "";
            
            if (name.includes(query) || category.includes(query)) {
                card.style.display = "flex";
                visibleCardsCount++;
            } else {
                card.style.display = "none";
            }
        });

        if (visibleCardsCount === 0 && query !== "") {
            section.style.display = "none";
        } else {
            section.style.display = "block";
        }
    });
}

